import { getProjectSnapshotByShareToken } from "@/lib/supabase/projects";
import { Icon } from "@/components/ui/icon";

/**
 * Public shared-walkthrough page (revamp Workstream 8.5 gap-fill) — the page
 * "Get shareable link" on the Walkthrough screen has always pointed at, which
 * didn't exist until now. Deliberately NOT behind auth: no `requireUser()`/
 * `getCurrentUser()` call here, this route is meant to be opened by a client
 * who was never given a Vastos login. The only gate is knowing the token
 * itself (see /api/share-link's comment on why that's an acceptable model).
 *
 * Video/image bytes are served through /api/s/[token]/asset, a separate
 * public route scoped to exactly this project's own keys — not the
 * authenticated /api/render?key= proxy every other page uses.
 */
export default async function SharedWalkthroughPage({
  params,
}: {
  params: Promise<{ token: string }>;
}) {
  const { token } = await params;
  const snapshot = await getProjectSnapshotByShareToken(token);

  if (!snapshot) {
    return (
      <div className="grid h-dvh place-items-center px-6 text-center">
        <div>
          <Icon name="CircleAlert" className="mx-auto size-8 text-faint" />
          <p className="mt-3 text-sm text-muted">This link isn&apos;t valid or has expired.</p>
        </div>
      </div>
    );
  }

  const project = snapshot.data;
  const wt = project.walkthrough;
  const hasVideo = wt?.status === "completed" && !!wt.videoKey;
  const rooms = project.floorPlan?.rooms ?? [];
  const approvedRooms = project.roomCards
    .filter((card) => card.included && card.approvedId)
    .map((card) => {
      const room = rooms.find((r) => r.id === card.roomId);
      const generation = card.generations.find((g) => g.id === card.approvedId);
      if (!room || !generation) return null;
      return { id: room.id, name: room.name, imageKey: generation.imageKey };
    })
    .filter((r): r is { id: string; name: string; imageKey: string } => !!r);

  const assetUrl = (key: string) => `/api/s/${token}/asset?key=${encodeURIComponent(key)}`;

  return (
    <div className="scrollbar-thin h-dvh overflow-y-auto bg-bg">
      <div className="mx-auto max-w-3xl px-6 py-12">
        <p className="text-xs font-medium uppercase tracking-wide text-faint">Vastos walkthrough</p>
        <h1 className="mt-1 text-2xl font-bold tracking-tight">{project.name}</h1>

        {hasVideo && wt?.videoKey && (
          <div className="mt-6">
            <video
              src={assetUrl(wt.videoKey)}
              controls
              className="w-full rounded-2xl border border-border"
            />
          </div>
        )}

        {approvedRooms.length > 0 && (
          <div className="mt-8">
            <h2 className="text-sm font-medium text-muted">Rooms</h2>
            <div className="mt-3 grid grid-cols-2 gap-3 sm:grid-cols-3">
              {approvedRooms.map((room) => (
                <div key={room.id} className="overflow-hidden rounded-xl border border-border bg-surface">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img
                    src={assetUrl(room.imageKey)}
                    alt={room.name}
                    className="aspect-[4/3] w-full object-cover"
                  />
                  <p className="truncate px-2.5 py-2 text-xs font-medium">{room.name}</p>
                </div>
              ))}
            </div>
          </div>
        )}

        {!hasVideo && approvedRooms.length === 0 && (
          <p className="mt-6 text-sm text-muted">This project doesn&apos;t have a finished walkthrough yet.</p>
        )}

        <p className="mt-12 text-center text-xs text-faint">Generated by Vastos</p>
      </div>
    </div>
  );
}
